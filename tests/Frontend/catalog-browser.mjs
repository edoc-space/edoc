/** Shared checks for the production catalogue route; receives a real Playwright Page. */
export async function verifyCatalog(page) {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const catalog = page.locator('[data-blocks-catalog]');
  await catalog.waitFor();
  const instances = catalog.locator('[data-catalog-instance]');
  assert(await instances.count() === 2, 'Two independent examples must exist');
  for (const group of ['colors', 'typography', 'buttons', 'badges', 'forms', 'cards', 'navigation', 'feedback', 'data', 'overlays', 'tokens']) {
    assert(await catalog.locator(`[data-catalog-group="${group}"]`).count() > 0, `Catalogue group ${group} is visible`);
  }
  assert(await catalog.locator('input[type="email"]').count() === 2, 'Email remains a local demo in each instance');
  assert(await catalog.getByRole('switch').count() === 2, 'Two accessible switches');
  assert(await catalog.getByRole('progressbar').count() > 0, 'Progress has a named state');
  assert(await catalog.locator('[data-catalog-skeleton]').count() > 0, 'Skeleton preview');
  const first = instances.nth(0);
  const second = instances.nth(1);
  await first.locator('[data-catalog-validate]').click();
  assert(await first.locator('input[aria-invalid="true"]').count() === 1, 'Validation exposes an invalid field');
  assert(await second.locator('input[aria-invalid="true"]').count() === 0, 'Validation stays local');
  const english = await page.locator('html').getAttribute('lang') === 'en';
  const t = (ru, en) => english ? en : ru;
  for (const [instance, name] of [[first, 'First'], [second, 'Second']]) {
    await instance.getByLabel(t('Название', 'Name')).fill(name);
    await instance.getByLabel(t('Заметка', 'Note'), { exact: true }).fill(name + ' note');
    await instance.getByLabel(t('Email для примера', 'Demo email'), { exact: true }).fill(name.toLowerCase() + '@example.com');
    await instance.getByRole('button', { name: t('Статус', 'Status'), exact: true }).click();
    await page.getByRole('option', { name: t('Готово', 'Ready'), exact: true }).click();
    await instance.getByRole('radio', { name: t('Большой', 'Large'), exact: true }).focus();
    await page.keyboard.press('Space');
    await instance.getByRole('checkbox', { name: t('Выбрать пример', 'Select example'), exact: true }).focus();
    await page.keyboard.press('Space');
    await instance.getByRole('switch').focus();
    await page.keyboard.press('Space');
  }
  await first.getByRole('button', { name: t('Сбросить', 'Reset'), exact: true }).focus();
  await page.keyboard.press('Enter');
  for (const label of [t('Название', 'Name'), t('Заметка', 'Note'), t('Email для примера', 'Demo email')]) {
    assert(await first.getByLabel(label, { exact: label !== t('Название', 'Name') }).inputValue() === '', 'Reset clears ' + label);
  }
  assert((await first.getByRole('button', { name: t('Статус', 'Status'), exact: true }).textContent()).includes(t('Черновик', 'Draft')), 'Reset restores select');
  assert(await first.getByRole('radio', { name: t('Маленький', 'Small'), exact: true }).isChecked(), 'Reset restores radio');
  assert(!await first.getByRole('checkbox').isChecked(), 'Reset clears checkbox');
  assert(await first.getByRole('switch').getAttribute('aria-checked') === 'false', 'Reset restores switch');
  assert(await first.locator('[aria-invalid="true"]').count() === 0, 'Reset clears validation');
  assert(await second.getByLabel(t('Заметка', 'Note'), { exact: true }).inputValue() === 'Second note', 'Second textarea survives reset');
  assert((await second.getByRole('button', { name: t('Статус', 'Status'), exact: true }).textContent()).includes(t('Готово', 'Ready')), 'Second select survives reset');
  assert(await second.getByRole('radio', { name: t('Большой', 'Large'), exact: true }).isChecked(), 'Second radio survives reset');
  assert(await second.getByRole('switch').getAttribute('aria-checked') === 'true', 'Second switch survives reset');
  for (const instance of [first, second]) await instance.getByRole('button', { name: t('Показать уведомление', 'Show notification'), exact: true }).click();
  const notices = page.locator('[data-catalog-notifications] [role="status"]');
  await notices.nth(1).waitFor();
  await page.waitForTimeout(500);
  assert(await notices.count() === 2, 'Two notifications stay open');
  const boxes = await notices.evaluateAll(nodes => nodes.map(node => { const r = node.getBoundingClientRect(); return { x:r.x,y:r.y,right:r.right,bottom:r.bottom }; }));
  assert(boxes[0].bottom <= boxes[1].y || boxes[1].bottom <= boxes[0].y || boxes[0].right <= boxes[1].x || boxes[1].right <= boxes[0].x, 'Notifications do not overlap after animation');
  const dismiss = notices.first().getByRole('button', { name: t('Закрыть', 'Close'), exact: true });
  await dismiss.focus(); await page.keyboard.press('Enter');
  await page.waitForTimeout(500);
  assert(await notices.count() === 1, 'Dismiss preserves the other notification');
  await notices.first().getByRole('button', { name: t('Закрыть', 'Close'), exact: true }).click();
  await page.waitForTimeout(500);
  const filters = first.locator('.collection-filter-options button');
  await filters.nth(1).click();
  assert((await first.locator('[data-catalog-filter-result]').textContent()).endsWith('1'), 'Local filter selects its own set');
  assert((await second.locator('[data-catalog-filter-result]').textContent()).endsWith('2'), 'The other filter remains independent');
  await filters.nth(2).click();
  assert(await first.locator('.collection-empty').count() === 1, 'Empty filter has an explicit state');
  await filters.nth(0).click();
  const firstTabs = first.getByRole('tab');
  const secondTabs = second.getByRole('tab');
  await firstTabs.nth(0).focus();
  await page.keyboard.press('ArrowRight');
  assert(await firstTabs.nth(1).getAttribute('aria-selected') === 'true', 'ArrowRight activates the next tab');
  assert(await secondTabs.nth(0).getAttribute('aria-selected') === 'true', 'The other tabs remain independent');
  await page.keyboard.press('Home');
  assert(await firstTabs.nth(0).getAttribute('aria-selected') === 'true', 'Home returns to the first tab');
  await page.keyboard.press('End');
  assert(await firstTabs.nth(1).getAttribute('aria-selected') === 'true', 'End activates the last tab');
  const increment = first.locator('[data-catalog-increment]');
  await increment.click();
  assert(await first.locator('[data-catalog-count]').textContent() === '1', 'Counter updates');
  assert(await second.locator('[data-catalog-count]').textContent() === '0', 'The other counter remains independent');
  const trigger = first.locator('[data-catalog-dialog-trigger]');
  await trigger.focus();
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  assert(Boolean(await dialog.getAttribute('aria-labelledby')), 'Dialog has an accessible name');
  assert(await dialog.evaluate(node => node.contains(document.activeElement)), 'Dialog receives focus');
  const stops = dialog.locator('button');
  await stops.first().focus();
  await page.keyboard.press('Shift+Tab');
  assert(await stops.last().evaluate(node => node === document.activeElement), 'Shift+Tab wraps to the final dialog action');
  await stops.last().focus();
  await page.keyboard.press('Tab');
  assert(await dialog.evaluate(node => node.contains(document.activeElement)), 'Tab remains in the dialog');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'detached' });
  assert(await trigger.evaluate(node => node === document.activeElement), 'Escape restores trigger focus');
  await trigger.click();
  await dialog.waitFor();
  await dialog.locator('[data-catalog-dialog-close]').click();
  await dialog.waitFor({ state: 'detached' });
  const tooltipTrigger = first.locator('[data-catalog-tooltip-trigger]');
  await tooltipTrigger.focus();
  const tooltip = page.getByRole('tooltip');
  await tooltip.waitFor().catch(error => { throw new Error('Tooltip did not open after keyboard focus', { cause: error }); });
  assert(await tooltipTrigger.evaluate(node => Boolean(document.getElementById(node.getAttribute('aria-describedby') ?? ''))), 'Tooltip describes its focused trigger');
  await page.keyboard.press('Escape');
  await tooltip.waitFor({ state: 'detached' });
  await tooltipTrigger.click();
  await tooltip.waitFor().catch(error => { throw new Error('Tooltip did not reopen after click', { cause: error }); });
  assert(await tooltipTrigger.evaluate(node => Boolean(document.getElementById(node.getAttribute('aria-describedby') ?? ''))), 'Tooltip describes its activated trigger');
  await page.keyboard.press('Escape');
  await tooltip.waitFor({ state: 'detached' });
  await tooltipTrigger.click();
  await tooltip.waitFor();
  await tooltipTrigger.click();
  await tooltip.waitFor({ state: 'detached' });
  assert(await catalog.locator('iframe').count() === 0, 'External video is not loaded before explicit intent');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Catalogue does not overflow the viewport');
  return { tabs: true, independentInstances: true, dialogFocus: true, tooltip: true, mediaOptIn: true, overflow: false };
}
